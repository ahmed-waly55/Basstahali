export function localStudentDay(date = new Date()): string {
  return [
    date.getFullYear(),
    String(date.getMonth() + 1).padStart(2, '0'),
    String(date.getDate()).padStart(2, '0'),
  ].join('-');
}

export function validStudentDay(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const [year, month, day] = value.split('-').map(Number);
  const parsed = new Date(year, month - 1, day);
  return (
    parsed.getFullYear() === year && parsed.getMonth() === month - 1 && parsed.getDate() === day
  );
}

export function safeLessonLink(value: string | null | undefined): string | null {
  if (!value) return null;
  try {
    const url = new URL(value);
    return url.protocol === 'https:' && !url.username && !url.password ? url.href : null;
  } catch {
    return null;
  }
}

export function studentStatus(value: string | null | undefined): string {
  const studentCopy = createStudentCopy();
  if (!value) return studentCopy.notProvided;
  const statuses: Record<string, string> = {
    scheduled: studentCopy.scheduled,
    confirmed: studentCopy.scheduled,
    completed: studentCopy.completed,
    cancelled: studentCopy.cancelled,
    canceled: studentCopy.cancelled,
    active: studentCopy.active,
    pending: studentCopy.pending,
    inactive: studentCopy.inactive,
    expired: studentCopy.expired,
    inprogress: studentCopy.inProgress,
    paid: studentCopy.paid,
    unpaid: studentCopy.unpaid,
  };
  return (
    statuses[value.toLowerCase().replace(/[ _-]/g, '')] ??
    (/^\d+$/.test(value) ? studentCopy.notProvided : value)
  );
}

export function studentDate(value: string | null | undefined, locale: string): string {
  const studentCopy = createStudentCopy();
  if (!value) return studentCopy.notProvided;
  const day = /^\d{4}-\d{2}-\d{2}$/.test(value);
  if (day && !validStudentDay(value)) return studentCopy.notProvided;
  const date = day
    ? new Date(Number(value.slice(0, 4)), Number(value.slice(5, 7)) - 1, Number(value.slice(8, 10)))
    : new Date(value);
  if (Number.isNaN(date.getTime())) return studentCopy.notProvided;
  return new Intl.DateTimeFormat(locale, {
    weekday: 'short',
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(date);
}

export function studentTime(value: string | null | undefined, locale: string): string {
  if (!value) return '';
  const match = /^(\d{1,2}):(\d{2})(?::\d{2}(?:\.\d+)?)?$/.exec(value);
  if (match && Number(match[1]) < 24 && Number(match[2]) < 60) {
    return new Intl.DateTimeFormat(locale, { hour: 'numeric', minute: '2-digit' }).format(
      new Date(2000, 0, 1, Number(match[1]), Number(match[2])),
    );
  }
  return value;
}
